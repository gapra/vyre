let totalWritten = 0;
const indexEntries = [];

for (const r of rules) {
  const dir = join(ROOT, r.cat);
  mkdirSync(dir, { recursive: true });
  const filePath = join(dir, `${r.id}.md`);

  const fm = `---
id: ${r.id}
category: ${r.cat}
title: ${r.title}
severity: ${r.severity}
refs: ${JSON.stringify(r.refs)}
---`;

  const body = `# ${r.title}

> ${r.summary}

**Severity:** \`${r.severity}\`

## Rule

${r.rule}

## Do

${r.do.map((d) => `- ${d}`).join("\n")}

## Don't

${r.dont.map((d) => `- ${d}`).join("\n")}

${r.refs.length ? `## References\n\n${r.refs.map((x) => `- \`${x}\``).join("\n")}\n` : ""}`;

  writeFileSync(filePath, `${fm}\n\n${body}\n`, "utf8");
  totalWritten++;
  indexEntries.push({
    id: r.id,
    category: r.cat,
    title: r.title,
    severity: r.severity,
    summary: r.summary,
    path: `references/ux-rules/${r.cat}/${r.id}.md`,
  });
}

const byCategory = indexEntries.reduce((acc, e) => {
  (acc[e.category] ||= []).push({ id: e.id, title: e.title, severity: e.severity, summary: e.summary, path: e.path });
  return acc;
}, {});

writeFileSync(
  join(ROOT, "_index.json"),
  JSON.stringify(
    {
      $schema: "https://gapra.dev/vyre/schemas/skill-index.json",
      total: totalWritten,
      categories: byCategory,
    },
    null, 2
  ),
  "utf8"
);

console.log(`✓ Generated ${totalWritten} UX rule files across ${Object.keys(byCategory).length} categories`);
for (const [cat, items] of Object.entries(byCategory)) {
  console.log(`  ${cat}: ${items.length}`);
}
